// Writes src/features/landing/science-coverage.generated.ts: the Science curriculum map the homepage draws, summarised
// from the curriculum packs that ship with the server (packages/tala-server/data/packs/science-*.json).
//
//   pnpm exec tsx scripts/home-coverage.mjs           write the file
//   pnpm exec tsx scripts/home-coverage.mjs --check   exit 1 when the file on disk differs from the packs
//
// Run it after any change to the Science curriculum packs. src/features/landing/coverage.test.ts makes the same
// comparison in the test run, so a stale file cannot be released.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { summarizeCurriculum } = await import('../src/features/landing/coverage.ts');

export const PACKS_DIR = join(here, '../../tala-server/data/packs');
export const OUT_FILE = join(here, '../src/features/landing/science-coverage.generated.ts');

export function sciencePacks(dir = PACKS_DIR) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')))
    .filter((p) => p.learningAreaId === 'science');
}

export function render(coverage) {
  return `/**
 * GENERATED by scripts/home-coverage.mjs from packages/tala-server/data/packs/science-*.json. Do not edit by hand.
 * The Science curriculum map of the homepage: competencies and weeks per grade and term, as the shipped curriculum
 * packs place them. coverage.test.ts fails when this file and the packs disagree.
 */
import type { ScienceCoverage } from './coverage';

export const SCIENCE_COVERAGE: ScienceCoverage = ${JSON.stringify(coverage, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = render(summarizeCurriculum(sciencePacks()));
  if (process.argv.includes('--check')) {
    const onDisk = readFileSync(OUT_FILE, 'utf8');
    if (onDisk !== text) {
      console.error('science-coverage.generated.ts is out of date: run `pnpm exec tsx scripts/home-coverage.mjs`.');
      process.exit(1);
    }
    console.log('science-coverage.generated.ts matches the curriculum packs.');
  } else {
    writeFileSync(OUT_FILE, text);
    const c = summarizeCurriculum(sciencePacks());
    console.log(`wrote ${OUT_FILE}: ${c.grades.length} grades, ${c.competencies} competencies, ${c.weeks} weeks`);
  }
}
