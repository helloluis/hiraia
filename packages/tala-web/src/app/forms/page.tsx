/**
 * `/forms`: public catalogue of fillable copies of DepEd School Forms (SF1–SF10 and ALS AF1–AF5).
 *
 * Static by design: the catalogue is data compiled into the release (./catalogue.ts) and every file is a static
 * asset under public/forms/. This page's own code reads no session, calls no API, stores nothing and has no upload
 * or submit path. (The root layout's shared providers still run here as on every page: one GET /api/v1/config,
 * cached in IndexedDB; no cookie.) Wording rules: these are unofficial drafting copies; they never replace the
 * LIS-generated forms.
 */
import type { Metadata } from 'next';
import type { ReactNode } from 'react';
import { PublicShell } from '@/features/landing/PublicShell';
import {
  BUILT_ON,
  FORMS,
  GROUPS,
  NOT_INCLUDED,
  OWNER_LABEL,
  SUMS_FILE,
  ZIP,
  type FormEntry,
  type GroupKey,
} from './catalogue';

export const dynamic = 'force-static';

export const metadata: Metadata = {
  title: 'DepEd school forms: fillable PDF copies',
  description:
    'Free, unofficial fillable PDF copies of DepEd School Forms SF1–SF10 and ALS forms AF1–AF5, made from DepEd’s own blank forms and printed samples. Not generated by the LIS.',
};

function size(bytes: number): string {
  return bytes >= 1024 * 1024 ? `${(bytes / (1024 * 1024)).toFixed(1)} MB` : `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

const TONE: Record<GroupKey, string> = {
  current: 'border-talaTeal text-talaTealText',
  previous: 'border-sage text-forest',
  'lis-newer': 'border-gold text-forest',
  recreated: 'border-talaTeal text-talaTealText',
  historical: 'border-brick text-brick',
  superseded: 'border-brick text-brick',
};

function Badge({ group }: { group: GroupKey }) {
  return (
    <span
      className={`inline-flex items-center rounded-full border-2 bg-white px-2.5 py-0.5 text-small font-medium ${TONE[group]}`}
    >
      {GROUPS[group].badge}
    </span>
  );
}

function Fact({ term, children }: { term: string; children: ReactNode }) {
  return (
    <>
      <dt className="text-forestMuted">{term}</dt>
      <dd className="min-w-0 break-words [overflow-wrap:anywhere]">{children}</dd>
    </>
  );
}

function FormCard({ f }: { f: FormEntry }) {
  return (
    <article
      id={f.id}
      className="flex flex-col gap-3 rounded border border-hairline bg-white p-4 shadow-card scroll-mt-24"
    >
      <div className="flex gap-4">
        <a href={f.file} className="shrink-0" aria-label={`Open ${f.code} (PDF)`}>
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={f.thumb.src}
            width={f.thumb.width}
            height={f.thumb.height}
            alt={`First page of ${f.code}, blank`}
            loading="lazy"
            decoding="async"
            className="h-auto w-[96px] wide:w-[132px] rounded-sm border border-hairline bg-white"
          />
        </a>
        <div className="flex min-w-0 flex-col gap-1.5">
          <p className="font-mono text-small text-forestMuted">{f.code}</p>
          <h3 className="font-display text-[1.125rem] leading-snug break-words [overflow-wrap:anywhere]">{f.title}</h3>
          <div className="flex flex-wrap gap-1.5">
            <Badge group={f.group} />
            <span className="inline-flex items-center rounded-full border border-hairline px-2.5 py-0.5 text-small">
              {OWNER_LABEL[f.owner]}
            </span>
            <span className="inline-flex items-center rounded-full border border-hairline px-2.5 py-0.5 text-small">
              {f.level}
            </span>
          </div>
        </div>
      </div>
      {f.note ? <p className="text-small leading-relaxed">{f.note}</p> : null}
      <dl className="grid grid-cols-[auto_1fr] gap-x-4 gap-y-1 text-small">
        <Fact term="Version">{f.version}</Fact>
        <Fact term="Made from">{f.source}</Fact>
        <Fact term="Paper">
          {f.paper} · {f.pages} {f.pages === 1 ? 'page' : 'pages'}
        </Fact>
        <Fact term="Fillable">
          {f.textFields} text {f.textFields === 1 ? 'box' : 'boxes'}
          {f.checkboxes ? ` · ${f.checkboxes} tick ${f.checkboxes === 1 ? 'box' : 'boxes'}` : ''}
        </Fact>
        <Fact term="SHA-256">
          <span className="font-mono text-[12px]">{f.sha256}</span>
        </Fact>
      </dl>
      <div className="flex flex-wrap items-center gap-2">
        <a
          href={f.file}
          download
          className="inline-flex min-h-touch items-center justify-center rounded bg-talaTeal px-4 py-2 font-medium text-white"
        >
          Download PDF ({size(f.bytes)})
        </a>
        <a
          href={f.file}
          className="inline-flex min-h-touch items-center justify-center rounded border-2 border-forest/20 px-4 py-2 font-medium"
        >
          Open
        </a>
      </div>
      <details className="group rounded border border-hairline">
        <summary className="flex min-h-touch cursor-pointer list-none items-center px-3 font-medium">
          Preview {f.pages === 1 ? 'the page' : `all ${f.pages} pages`}
        </summary>
        <div className="flex flex-col gap-3 p-3">
          {f.previews.map((p, i) => (
            // eslint-disable-next-line @next/next/no-img-element
            <img
              key={p.src}
              src={p.src}
              width={p.width}
              height={p.height}
              alt={`${f.code}, page ${i + 1} of ${f.pages}, blank`}
              loading="lazy"
              decoding="async"
              className="h-auto w-full rounded-sm border border-hairline bg-white"
            />
          ))}
        </div>
      </details>
    </article>
  );
}

export default function FormsPage() {
  const order = Object.keys(GROUPS) as GroupKey[];
  return (
    <PublicShell>
      <div lang="en" className="px-4 py-8 wide:px-8 wide:py-14">
        <div className="mx-auto flex max-w-5xl flex-col gap-8">
          <header className="flex flex-col gap-4">
            <p className="text-kicker uppercase text-talaTealText">Free · for drafting and practice</p>
            <h1 className="font-display text-[2rem] leading-tight wide:text-[2.75rem] break-words [overflow-wrap:anywhere]">
              DepEd school forms: fillable PDF copies
            </h1>
            <p className="text-read max-w-measure">
              Fillable PDF copies of DepEd School Forms SF1–SF10, their Kindergarten and Senior High School versions,
              and the ALS forms AF1–AF5. Each one is made from DepEd’s own blank file (the two SF9 report cards from
              the sample DepEd printed in DO 8, s. 2015), keeping its layout, labels, instructions, paper size and
              signature spaces. Type into them in any PDF app that fills forms, save them, and print them.
            </p>
          </header>

          <section
            aria-labelledby="notice"
            className="flex flex-col gap-2 rounded border-l-4 border-brick border bg-white p-4"
          >
            <h2 id="notice" className="font-display text-[1.25rem]">
              Unofficial copies — not a replacement for the LIS
            </h2>
            <ul className="flex list-disc flex-col gap-1.5 pl-5 text-read">
              <li>
                These are unofficial copies. The official SF1, SF2, SF4, SF5 and SF6 are generated in DepEd’s Learner
                Information System (LIS) (DO 11, s. 2018). DepEd says “electronic school forms” from anywhere else are
                null and void for official transactions.
              </li>
              <li>
                Use them to draft, practise and prepare offline. A teacher must check and approve everything before it
                becomes an official record.
              </li>
              <li>
                Nothing you type is sent anywhere. The files contain no scripts or links and never submit or upload.
                Signatures are always handwritten on paper.
              </li>
              <li>Free, and never for sale. Each printed page carries a small note saying so.</li>
            </ul>
          </section>

          <section aria-labelledby="all" className="flex flex-col gap-3 rounded border border-hairline bg-white p-4">
            <h2 id="all" className="font-display text-[1.25rem]">
              All {FORMS.length} forms in one file
            </h2>
            <p className="text-read">
              A ZIP file with every PDF on this page, byte for byte. Each file’s SHA-256 checksum is listed under it
              below and in{' '}
              <a href={SUMS_FILE} className="underline">
                SHA256SUMS
              </a>
              .
            </p>
            <div className="flex flex-wrap items-center gap-3">
              <a
                href={ZIP.file}
                download
                className="inline-flex min-h-touch items-center justify-center rounded bg-talaTeal px-5 py-3 font-medium text-white"
              >
                Download all {ZIP.count} PDFs ({size(ZIP.bytes)})
              </a>
            </div>
            <p className="text-small text-forestMuted break-all">
              SHA-256 <span className="font-mono">{ZIP.sha256}</span>
            </p>
          </section>

          <nav aria-label="Sections" className="flex flex-col gap-2">
            <h2 className="font-display text-[1.25rem]">What is here</h2>
            <ul className="flex flex-col gap-2">
              {order.map((g) => {
                const n = FORMS.filter((f) => f.group === g).length;
                return n ? (
                  <li key={g} className="flex flex-wrap items-baseline gap-2">
                    <a href={`#${g}`} className="font-medium underline">
                      {GROUPS[g].title}
                    </a>
                    <span className="text-small text-forestMuted">
                      {n} {n === 1 ? 'form' : 'forms'}
                    </span>
                  </li>
                ) : null;
              })}
            </ul>
          </nav>

          {order.map((g) => {
            const list = FORMS.filter((f) => f.group === g);
            if (!list.length) return null;
            return (
              <section key={g} id={g} aria-labelledby={`${g}-h`} className="flex flex-col gap-4 scroll-mt-24">
                <div className="flex flex-col gap-1.5">
                  <h2 id={`${g}-h`} className="font-display text-headline">
                    {GROUPS[g].title}
                  </h2>
                  <p className="text-read max-w-measure">{GROUPS[g].explain}</p>
                </div>
                <div className="grid grid-cols-1 gap-4 wide:grid-cols-2">
                  {list.map((f) => (
                    <FormCard key={f.id} f={f} />
                  ))}
                </div>
              </section>
            );
          })}

          <section aria-labelledby="missing" className="flex flex-col gap-2 rounded border border-hairline bg-white p-4">
            <h2 id="missing" className="font-display text-[1.25rem]">
              Not available here
            </h2>
            <ul className="flex list-disc flex-col gap-1.5 pl-5 text-read">
              {NOT_INCLUDED.map((t) => (
                <li key={t}>{t}</li>
              ))}
            </ul>
          </section>

          <section aria-labelledby="howto" className="flex flex-col gap-2">
            <h2 id="howto" className="font-display text-[1.25rem]">
              How to use them
            </h2>
            <ol className="flex list-decimal flex-col gap-1.5 pl-5 text-read">
              <li>Open the PDF in an app that can fill PDF forms, type into the boxes, and save.</li>
              <li>
                Print at 100% (“Actual size”) on the paper listed for the form. DepEd allows A4 or long (8.5 × 13 in)
                bond paper in black ink.
              </li>
              <li>Sign by hand. Totals, averages and BMI are not calculated for you: work them out and check them.</li>
              <li>
                Once a file is filled in, it holds learners’ personal information. Keep it on school devices and do not
                upload it anywhere.
              </li>
            </ol>
            <p className="text-small text-forestMuted">
              Tested on {BUILT_ON} in five PDF engines: the ones behind Firefox, Chrome, desktop Linux viewers and
              printing. Phone apps were not tested; check one form on your phone before relying on it.
            </p>
          </section>
        </div>
      </div>
    </PublicShell>
  );
}
