// Generate a slug→category lookup so the image retriever can scope matches to the grounded
// fact's science domain (no word-association cross-domain mismatches). Category = the
// assets-png/<category>/ folder.
//
// Walks packages/images/assets-png DIRECTLY — deliberately NOT imageMap.ts. IMAGE_MAP is the
// 140 MB art-pack head (scripts/build-art-pack.mts), but imageDomainScope
// (packages/shared/src/rag/images.ts) reads a MISSING category as 'general', which is admitted
// into every domain — so pruning this table with the bundle would change which slug WINS the
// cosine scan, and the ranking is documented (and was measured) as pool-independent: presence
// is an admission test on the winner, never a ranking input. The full table is ~4.2k string
// pairs of JS, no PNG bytes ride on it.
//
// Dedup matches gen-image-map.mjs's slugPath exactly: sorted file paths, first slug wins
// (e.g. biology/ beats flagged/ for the 43 flagged-folder duplicates).
// Run: node scripts/gen-image-category.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const MOBILE = new URL('..', import.meta.url).pathname;
const IMAGES = join(MOBILE, '../images/assets-png');
const OUT = join(MOBILE, 'src/generated/imageCategory.generated.ts');

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir)) {
    if (e.startsWith('.')) continue;
    const p = join(dir, e);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (e.toLowerCase().endsWith('.png')) out.push(p);
  }
  return out;
}

const out = {};
for (const f of walk(IMAGES).sort()) {
  const slug = basename(f, '.png');
  if (slug in out) continue; // first (sorted) path wins, same as gen-image-map's slugPath
  out[slug] = f.slice(IMAGES.length + 1).split('/')[0];
}
const body =
  '// AUTO-GENERATED by scripts/gen-image-category.mjs — do not edit.\n' +
  '// slug → image catalog category (folder), for domain-scoped image retrieval.\n' +
  '// Spans the FULL clip-art catalog, not the bundled art pack: imageDomainScope reads a\n' +
  "// missing category as 'general', so pruning this table would change scan winners.\n" +
  '/* eslint-disable */\n' +
  'export const IMAGE_CATEGORY: Record<string, string> = ' +
  JSON.stringify(out) +
  ';\n';
writeFileSync(OUT, body);
const counts = {};
for (const c of Object.values(out)) counts[c] = (counts[c] || 0) + 1;
console.log(Object.keys(out).length, 'images categorized:', counts);
