export function activityStrings(language: 'fil' | 'en') {
  const table = language === 'fil' ? activityFil : activityEn;
  return (key: ActivityStringKey, vars: Record<string, string | number> = {}): string =>
    table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export type ActivityT = ReturnType<typeof activityStrings>;
