/**
 * Protocol test vectors shared with the Kotlin unit tests (modules/tala-activity/vectors/
 * protocol-vectors.json). Deterministic: a fixed RSA key, fixed nonces and a fixed OAEP seed, so the
 * JVM side can check that javax.crypto's RSA/ECB/OAEPPadding(SHA-256, MGF1-SHA1) unwraps exactly
 * what the student side (and this file's Android-true padding) produce. Run with WRITE_VECTORS=1 to
 * regenerate after a deliberate protocol change; otherwise the committed file must match.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  publicEncrypt,
  constants,
} from 'node:crypto';
import { aesGcmEncrypt, manual, oaepPad, sha256Sync } from './nodeCrypto';
import {
  b64urlEncode,
  classHint,
  generatedClassName,
  qrPayload,
  replyBody,
  utf8,
} from './protocol';

const FILE = resolve('modules/tala-activity/vectors/protocol-vectors.json');

type Vectors = {
  note: string;
  rsa: { privateKeyPkcs8Pem: string; publicKeySpkiB64url: string };
  hints: { classId: string; hint: string; endpointName: string }[];
  classNames: { classId: string; generated: string }[];
  qr: { classId: string; className: string; payload: string };
  envelope: {
    challenge: string;
    sessionKeyB64url: string;
    oaepSeedHex: string;
    wrappedKeyB64url: string;
    nonceB64url: string;
    plaintext: string;
    ciphertextB64url: string;
  };
  reply: {
    sessionKeyB64url: string;
    challenge: string;
    type: string;
    nonceB64url: string;
    plaintext: string;
    outerJson: string;
  };
  manual: {
    code: string;
    challenge: string;
    clientNonceB64url: string;
    secretB64url: string;
    proofB64url: string;
    responseKeyB64url: string;
    responseAadB64url: string;
    qrPayload: string;
    replyNonceB64url: string;
    manualKeyJson: string;
  };
};

const fixed = (n: number, seed: number) => new Uint8Array(n).map((_, i) => (i * 37 + seed) & 0xff);

async function build(privateKeyPem?: string): Promise<Vectors> {
  const pair = privateKeyPem
    ? {
        privateKey: createPrivateKey(privateKeyPem),
        publicKey: createPublicKey(createPrivateKey(privateKeyPem)),
      }
    : generateKeyPairSync('rsa', { modulusLength: 2048 });
  const pem = pair.privateKey.export({ type: 'pkcs8', format: 'pem' }) as string;
  const spki = b64urlEncode(
    new Uint8Array(pair.publicKey.export({ type: 'spki', format: 'der' }) as Buffer)
  );
  const sha = async (b: Uint8Array) => sha256Sync(b);
  const classIds = ['0f8fad5b-d9cb-469f-a165-70867728950e', '7c9e6679-7425-40de-944b-e07fc1f90ae7'];
  const hints = [];
  for (const id of classIds) {
    const hint = await classHint(id, sha);
    hints.push({ classId: id, hint, endpointName: `Hiraia Tala 2 ${hint}` });
  }
  const classNames = [];
  for (const id of classIds)
    classNames.push({ classId: id, generated: await generatedClassName(id, sha) });

  const challenge = b64urlEncode(fixed(24, 5));
  const sessionKey = fixed(32, 11);
  const seed = fixed(32, 99);
  const wrapped = publicEncrypt(
    { key: pair.publicKey, padding: constants.RSA_NO_PADDING },
    Buffer.from(oaepPad(sessionKey, seed))
  );
  const nonce = fixed(12, 3);
  const plaintext = JSON.stringify({
    schema: 1,
    class_id: classIds[0],
    installation_id: 'installation-123456789',
    challenge,
    profiles: [{ id: 'student-profile-111111111', name: 'Ana' }],
    events: [],
  });
  const ciphertext = aesGcmEncrypt(sessionKey, nonce, utf8(challenge), utf8(plaintext));

  const replyNonce = fixed(12, 7);
  const replyPlain = replyBody(challenge, ['card-event-123456789'], [], 'Perseverance');
  const replySealed = aesGcmEncrypt(sessionKey, replyNonce, utf8(challenge), utf8(replyPlain));

  const code = 'ABCDEFGHJKMN';
  const clientNonce = fixed(16, 21);
  const secret = manual.secret(code);
  const qr = qrPayload(classIds[0]!, 'Perseverance', spki);
  const manualNonce = fixed(12, 13);
  const manualSealed = aesGcmEncrypt(
    manual.responseKey(secret, challenge, clientNonce),
    manualNonce,
    manual.aad(challenge, clientNonce),
    utf8(qr)
  );

  return {
    note: 'Generated by src/features/activity/vectors.test.ts (WRITE_VECTORS=1). Shared with the Kotlin tests.',
    rsa: { privateKeyPkcs8Pem: pem, publicKeySpkiB64url: spki },
    hints,
    classNames,
    qr: { classId: classIds[0]!, className: 'Perseverance', payload: qr },
    envelope: {
      challenge,
      sessionKeyB64url: b64urlEncode(sessionKey),
      oaepSeedHex: Buffer.from(seed).toString('hex'),
      wrappedKeyB64url: b64urlEncode(new Uint8Array(wrapped)),
      nonceB64url: b64urlEncode(nonce),
      plaintext,
      ciphertextB64url: b64urlEncode(ciphertext),
    },
    reply: {
      sessionKeyB64url: b64urlEncode(sessionKey),
      challenge,
      type: 'ack',
      nonceB64url: b64urlEncode(replyNonce),
      plaintext: replyPlain,
      outerJson: JSON.stringify({
        v: 1,
        type: 'ack',
        nonce: b64urlEncode(replyNonce),
        ciphertext: b64urlEncode(replySealed),
      }),
    },
    manual: {
      code,
      challenge,
      clientNonceB64url: b64urlEncode(clientNonce),
      secretB64url: b64urlEncode(secret),
      proofB64url: b64urlEncode(manual.proof(secret, challenge, clientNonce)),
      responseKeyB64url: b64urlEncode(manual.responseKey(secret, challenge, clientNonce)),
      responseAadB64url: b64urlEncode(manual.aad(challenge, clientNonce)),
      qrPayload: qr,
      replyNonceB64url: b64urlEncode(manualNonce),
      manualKeyJson: JSON.stringify({
        v: 1,
        type: 'manual_key',
        nonce: b64urlEncode(manualNonce),
        ciphertext: b64urlEncode(manualSealed),
      }),
    },
  };
}

test('the committed protocol vectors are reproducible from the same key', async () => {
  if (!existsSync(FILE) || process.env.WRITE_VECTORS) {
    const fresh = await build();
    writeFileSync(FILE, JSON.stringify(fresh, null, 2) + '\n');
  }
  const committed = JSON.parse(readFileSync(FILE, 'utf8')) as Vectors;
  const rebuilt = await build(committed.rsa.privateKeyPkcs8Pem);
  assert.deepEqual(rebuilt, committed);
  assert.equal(committed.hints[0]!.hint, 'WlOusN1s');
  assert.equal(committed.hints[1]!.hint, 'x3ejyN5T');
});
