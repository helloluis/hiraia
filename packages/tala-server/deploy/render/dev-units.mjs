#!/usr/bin/env node
/**
 * Tala slide pictures on a DEVELOPER'S machine, without root: the same job program, the same protocol and the same
 * sandbox lines as production, run by the per-user service manager (`systemctl --user`). The units are DERIVED from
 * the production unit files beside this script (units.mjs), so what is tested here is what is installed there,
 * minus the list this script prints.
 *
 * NOT for a production host, and it refuses to run as root. Only root's service manager can give drawing a user of
 * its own; here a job runs as the developer, can see the developer's other processes, and says so in its report
 * (`isolation: "shared-user"`). The web app accepts that only with TALA_DECKS_PREVIEW_SHARED_USER=1, and never when
 * TALA_ENV is staging or production.
 *
 *   node dev-units.mjs start [--name tala-render-dev] [--soffice-dir DIR] [--fonts-dir DIR]
 *                            [--set Key=Value]... [--drop Key]... [--bind SRC:DST]... [--exec "/abs/program arg..."]
 *   node dev-units.mjs stop  [--name tala-render-dev]
 *   node dev-units.mjs path  [--name tala-render-dev]          the socket to give TALA_DECKS_PREVIEW_SOCKET
 *
 * --soffice-dir   a LibreOffice folder that has program/soffice.bin, when it is not the system's /usr/lib/libreoffice
 * --fonts-dir     extra fonts for the job (for example Carlito and Caladea)
 * --userland DIR  rehearse another machine: DIR is an unpacked copy of its packages (usr/, etc/fonts, ...) and takes
 *                 the place of this machine's programs at the production paths
 * --set, --drop   change or remove one [Service] line: for tests that need a tiny ceiling, never for real use
 * --add           one more InaccessiblePaths=/ReadOnlyPaths=/NoExecPaths= line, for a test
 * --exec          start another program for each connection instead of the job
 *
 * Nothing is written outside $XDG_RUNTIME_DIR, so a logout or reboot removes it; `stop` removes it now.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { developerLines, here, readArgs, userManagerGroup, withOwnGroup } from './units.mjs';

function fail(message) {
  console.error(`dev-units: ${message}`);
  process.exit(2);
}
let parsed;
try {
  parsed = readArgs(process.argv.slice(2), ['set', 'drop', 'bind', 'add']);
} catch (err) {
  fail(err.message);
}
const command = parsed.rest[0];
const options = { name: 'tala-render-dev', ...parsed.options };
if (!['start', 'stop', 'path'].includes(command)) fail('usage: dev-units.mjs start|stop|path [options] (see the top of this file)');
if (process.getuid() === 0) fail('this is the developer set-up and does not run as root. On a server use install.sh.');
if (!/^[a-z][a-z0-9-]{2,40}$/.test(options.name)) fail('--name: lower-case letters, digits and dashes');
const runtime = process.env.XDG_RUNTIME_DIR;
if (!runtime || !fs.existsSync(runtime)) fail('no XDG_RUNTIME_DIR: this needs a login session with a per-user service manager');

const name = options.name;
const slice = `${name.replace(/-/g, '')}.slice`;
const unitDir = path.join(runtime, 'systemd', 'user');
const stateDir = path.join(runtime, name);
const socketPath = path.join(stateDir, 'render.sock');
const units = { service: path.join(unitDir, `${name}@.service`), socket: path.join(unitDir, `${name}.socket`), slice: path.join(unitDir, slice) };
const systemctl = (...args) => execFileSync('systemctl', ['--user', ...args], { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });

if (command === 'path') {
  console.log(socketPath);
  process.exit(0);
}
if (command === 'stop') {
  for (const unit of [`${name}.socket`, `${name}@*.service`, slice]) {
    try {
      systemctl('stop', unit);
    } catch {
      /* not running */
    }
  }
  for (const file of Object.values(units)) fs.rmSync(file, { force: true });
  fs.rmSync(stateDir, { recursive: true, force: true });
  systemctl('daemon-reload');
  console.log(`stopped and removed ${name}`);
  process.exit(0);
}

/* ---- start ---- */
let dev;
try {
  dev = developerLines({ sofficeDir: options.sofficeDir, fontsDir: options.fontsDir, userland: options.userland, set: options.set, drop: options.drop, add: options.add, binds: options.bind, stateDir });
  // The job's own control group is under the per-user manager here, in this set-up's own slice.
  dev.lines = withOwnGroup(dev.lines, { root: userManagerGroup(), slice });
} catch (err) {
  fail(err.message);
}
const differences = [...dev.differences];
if (options.exec) differences.push(`each connection starts another program instead of the job: ${options.exec}`);
const service = [
  `# Generated by dev-units.mjs from ${path.join(here, 'tala-render@.service')}. Developer machine only.`,
  '[Unit]',
  `Description=Tala slide pictures (${name}): one sandboxed drawing job`,
  'CollectMode=inactive-or-failed',
  '',
  '[Service]',
  ...dev.lines.map((line) => (line.startsWith('ExecStart=') ? `ExecStart=${options.exec ?? `${dev.node} ${dev.job}`}` : line.startsWith('Slice=') ? `Slice=${slice}` : line.startsWith('SyslogIdentifier=') ? `SyslogIdentifier=${name}` : line)),
  '',
].join('\n');
const socket = fs
  .readFileSync(path.join(here, 'tala-render.socket'), 'utf8')
  .split('\n')
  .filter((line) => !/^Socket(User|Group)=/.test(line))
  .map((line) => (line.startsWith('ListenStream=') ? `ListenStream=${socketPath}` : line.startsWith('SocketMode=') ? 'SocketMode=0600' : line))
  .join('\n');
differences.push('the socket belongs to you alone (0600), not to root and the web app group');

fs.mkdirSync(unitDir, { recursive: true });
fs.mkdirSync(stateDir, { recursive: true, mode: 0o700 });
fs.writeFileSync(units.service, service);
fs.writeFileSync(units.socket, socket);
fs.writeFileSync(units.slice, fs.readFileSync(path.join(here, 'talarender.slice'), 'utf8'));
systemctl('daemon-reload');
try {
  systemctl('stop', `${name}.socket`);
} catch {
  /* was not running */
}
systemctl('start', `${name}.socket`);
console.log(`socket: ${socketPath}`);
console.log(`units:  ${Object.values(units).join('\n        ')}`);
console.log('Differences from the production units:');
for (const d of differences) console.log(`  - ${d}`);
