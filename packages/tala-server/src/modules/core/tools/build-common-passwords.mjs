#!/usr/bin/env node
/**
 * Rebuilds ../common-passwords.generated.ts from public lists of commonly used / breached passwords.
 * OWNER: workstream A. Not run by the build or the tests; run by hand when the list should be refreshed.
 *
 *   node build-common-passwords.mjs <file> [<file> ...]
 *
 * Inputs are plain text, one password per line. Sources used for the committed file (both from the
 * SecLists project, MIT licence, https://github.com/danielmiessler/SecLists, Passwords/Common-Credentials/):
 *   - 100k-most-used-passwords-NCSC.txt   (UK NCSC top 100,000, derived from Have I Been Pwned)
 *   - xato-net-10-million-passwords-100000.txt
 *
 * Only entries of 10 or more characters are kept, because Tala's minimum password length is 10 (AUTH-2):
 * anything shorter is already refused. Entries are lower-cased; the check is case-insensitive.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const MIN = 10;
const MAX = 64;
const files = process.argv.slice(2);
if (files.length === 0) {
  console.error('usage: node build-common-passwords.mjs <file> [<file> ...]');
  process.exit(2);
}
const set = new Set();
for (const file of files) {
  for (const raw of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const p = raw.normalize('NFKC').toLowerCase();
    if (p.length < MIN || p.length > MAX) continue;
    if (p.startsWith('$hex[')) continue; // encoding artefacts in the source lists, not passwords
    if (/[\u0000-\u001f\u007f]/.test(p)) continue;
    set.add(p);
  }
}
const list = [...set].sort();
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'common-passwords.generated.ts');
const header = `/**
 * GENERATED by tools/build-common-passwords.mjs. Do not edit by hand.
 * ${list.length} commonly used or breached passwords of ${MIN}+ characters, lower-cased, newline-separated.
 * Sources: SecLists (MIT licence, (c) Daniel Miessler and contributors), Passwords/Common-Credentials:
 * the UK NCSC top-100k list derived from Have I Been Pwned, and the xato.net top-100k list.
 * Used only as a deny-list at sign-up and password change (PRD AUTH-2). No lookup leaves the server.
 */
`;
writeFileSync(out, `${header}export const COMMON_PASSWORDS_TEXT: string = ${JSON.stringify(list.join('\n'))};\n`);
console.log(`wrote ${list.length} entries to ${out}`);
