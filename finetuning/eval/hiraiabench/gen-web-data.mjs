#!/usr/bin/env node
/**
 * Emit the web data module (packages/web/src/components/hiraiabench-data.ts) from bench-results.json.
 * Re-run whenever results change (e.g. after adding a model). Rounds to 1 decimal; honest footnotes.
 * Usage: node gen-web-data.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const r = JSON.parse(readFileSync(join(HERE, 'bench-results.json'), 'utf8'));
const CATS = ['Science Accuracy', 'Tagalog Fluency', 'English Fluency', 'Bisaya', 'Pedagogy', 'Safety & Honesty', 'Code-switching'];

// display order BIGGEST → SMALLEST, so scores descend with size — EXCEPT Hiraia, our 3B fine-tune,
// which bucks the trend (it sits at the 3B rung, right above its untrained Sailor2-3B base, but scores
// like a much larger model). Hiraia is highlighted + carries the cat mark.
const ORDER = [
  ['opus-4.8', 'Claude Opus 4.8', 'cloud frontier (reference ceiling)', false],
  ['qwen3.5-27b', 'Qwen3.5-27B', 'recent open model, ~9× our size', false],
  ['qwen3.5-9b', 'Qwen3.5-9B', 'recent open model, ~3× our size', false],
  ['hiraia-v7', 'Hiraia', 'our on-device 3B fine-tune (Sailor2-3B + LoRA)', true],
  ['sailor2-3b', 'Sailor2-3B', 'our untrained 3B base', false],
  ['qwen3-1.7b', 'Qwen3-1.7B', 'untrained small base', false],
];
const rows = ORDER.filter(([k]) => r[k]).map(([k, model, note, highlight]) => ({
  model, note, highlight,
  scores: CATS.map((c) => (r[k][c] == null ? null : Math.round(r[k][c] * 10) / 10)),
}));

// Honest per-category notes — each reflects how the score is ACTUALLY computed (aggregate.mjs:
// a projection of the 5-dim judge rubric over a probe subset). Order matches CATS.
const category_notes = [
  { name: 'Science Accuracy', note: 'Is the science correct and pitched for a 5th-grader? A confident wrong answer or an affirmed myth scores near zero — accuracy outranks fluency.' },
  { name: 'Tagalog Fluency', note: 'How natural, warm, and age-appropriate the Tagalog reads for a child — tutor register, not just grammar. A fluent but stiff, essay-style answer scores lower than a simple, friendly one.' },
  { name: 'English Fluency', note: 'The same register and clarity test, for questions a student asks in English.' },
  { name: 'Bisaya', note: 'Cebuano answers, judged on both natural register and factual correctness — the hardest language for most models.' },
  { name: 'Pedagogy', note: 'Does it actually teach? Simple words, builds intuition, and encourages the child — without dumbing the science down into wrongness.' },
  { name: 'Safety & Honesty', note: 'Gently corrects common myths and gives safe everyday answers — and honestly says “I’m not sure” on genuinely unknowable questions (tomorrow’s weather, a lottery number) instead of inventing one.' },
  { name: 'Code-switching', note: 'Filipino kids mix Tagalog and English mid-sentence (“Taglish”). This measures whether the tutor follows that naturally and still answers well.' },
];

const meta = {
  n_probes: 59,
  categories: CATS,
  category_notes,
  methodology:
    'Single-turn probes from our internal capability suite (no retrieval/RAG), one shared neutral tutor prompt for every model, blind comparative LLM-judging (answers anonymized, scored 0-5 on accuracy/helpfulness/faithfulness/naturalness/pedagogy, then projected to the 7 categories).',
  footnotes: [
    'Qwen3.5 ships in many sizes (0.8B–72B + a 30B-A3B MoE); we show 9B (~3× our size) and 27B (~9×) as open references. No 14B exists in this generation.',
    'Open models run at their on-device Q4_K_M (llama.cpp), the quant a deployer would actually use; Hiraia is the shipped 3B + LoRA.',
    'No RAG: every model answers from its own weights under the same tutor prompt. Hiraia’s product adds retrieval grounding on top — not reflected here.',
    'Hiraia’s Bisaya here uses the tl/en LoRA (cross-lingual transfer); the product ships a separate Bisaya adapter, not benchmarked.',
    'Claude Opus 4.8 saturates the rubric (5.0) — it is the frontier reference ceiling, not a same-class model. Qwen3.5-27B was scored against the other five as frozen calibration anchors.',
  ],
};

writeFileSync(
  join(HERE, '../../../packages/web/src/components/hiraiabench-data.ts'),
  '// AUTO-GENERATED by finetuning/eval/hiraiabench/gen-web-data.mjs (do not hand-edit).\n' +
    'export type BenchRow = { model: string; note: string; highlight: boolean; scores: (number|null)[] };\n' +
    'export const BENCH_META = ' + JSON.stringify(meta, null, 2) + ' as const;\n' +
    'export const BENCH_CATEGORIES = ' + JSON.stringify(CATS) + ' as const;\n' +
    'export const BENCH_ROWS: BenchRow[] = ' + JSON.stringify(rows, null, 2) + ';\n'
);
console.log(`wrote hiraiabench-data.ts (${rows.length} rows:`, rows.map((x) => x.model).join(', ') + ')');
